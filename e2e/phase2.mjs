  await text.press('Control+Enter')
  check('finish creates one editable text object', await fw(page, w => w.board.doc.items.length === 1 && w.board.doc.items[0].t === 't' && !w.S.editing.value))
  await page.getByRole('button', { name: 'Object style', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Font size' }).fill('30')
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
