  await page.getByRole('button', { name: 'Fill #d7f0dd', exact: true }).click()
  await page.getByRole('button', { name: 'dashed border', exact: true }).click()
  await page.getByRole('slider', { name: 'Corners', exact: true }).evaluate(el => { el.value = '18'; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })) })
  check('shape labels and border controls persist together', await fw(page, w => { const s = w.board.selection[0]; return s.text === 'Start with an idea' && s.fill === '#d7f0dd' && s.dash === 'dashed' && s.radius === 18 }))
  await page.getByRole('button', { name: 'No fill', exact: true }).click()
  await saved()
  check('No fill is a valid saveable style', await fw(page, w => w.board.selection[0].fill === 'none' && !w.S.saveError.value))
  await page.getByRole('button', { name: 'Fill #d7f0dd', exact: true }).click()
  await screenshot('phase2-object-style')
  await page.keyboard.press('Escape')
  await fw(page, w => w.board.setSelection([w.board.doc.items.find(it => it.t === 'h')]))

