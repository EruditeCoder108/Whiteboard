  await page.keyboard.press('PageUp')
  check('front ordering is undoable without losing selection', await fw(page, w => w.board.doc.items.at(-1) === w.board.selection[0] && w.board.selection[0].text.startsWith('A better')))
  await page.keyboard.press('Control+z')
  await fw(page, w => { w.board.setView({ x: 120, y: 80, zoom: .65 }); w.board.setSelection([w.board.doc.items[0]]) })
  await page.keyboard.press('Enter')
  check('inline editing follows the board position and zoom', await page.locator('.inline-editor').evaluate(el => { const r = el.getBoundingClientRect(), { board } = window.__fw, it = window.__fw.S.editing.value.item; return Math.abs(r.left - (it.p[0] - board.view.x) * board.view.zoom) < 1 && Math.abs(r.width - (it.p[2] - it.p[0]) * board.view.zoom) < 1 }))
  await page.keyboard.press('Escape')
  await fw(page, w => w.board.setView({ x: 0, y: 0, zoom: 1 }))
  const textBounds = await selectBox(), originalText = await fw(page, w => structuredClone(w.board.selection[0]))
  await gesture(page, [[textBounds[2], (textBounds[1] + textBounds[3]) / 2], [textBounds[2] - 150, (textBounds[1] + textBounds[3]) / 2]])
  check('narrowing text preserves font size and grows to fit wrapped content', await fw(page, (w, before) => { const it = w.board.selection[0]; return it.fontSize === before.fontSize && it.p[2] - it.p[0] < before.p[2] - before.p[0] - 100 && it.p[3] - it.p[1] > before.p[3] - before.p[1] }, originalText))
  await page.keyboard.press('Control+z')
  await fw(page, w => w.board.setSelection([w.board.doc.items.find(it => it.t === 'h')]))
  const beforeCancelledDrag = await fw(page, w => JSON.stringify(w.board.selection[0]))
  await gesture(page, [[770, 240], [790, 265]], { up: false })
  await page.keyboard.press('Escape')
  await gesture(page, [[790, 265]], { down: false })
  check('Escape cancels an active drag without changing the object', await fw(page, (w, before) => !w.S.gestureActive.value && JSON.stringify(w.board.doc.items.find(it => it.t === 'h')) === before, beforeCancelledDrag))
  await page.mouse.dblclick(770, 240)
  check('double-click opens a shape label for editing', await page.getByRole('textbox', { name: 'Shape label' }).isVisible())
  await page.keyboard.press('Escape')
  await fw(page, w => w.board.setSelection([w.board.doc.items.find(it => it.note)]))
  await saved()
  const json = await fw(page, w => w.board.serialize())
  check('saved format includes editable Phase 2 objects', JSON.parse(json).version === 2 && JSON.parse(json).items.length === 3)
  const png = await fw(page, async w => Array.from(new Uint8Array(await w.board.exportPng('#ffffff', true))))
  writeFileSync(join(shotDir, 'phase2-export.png'), Buffer.from(png))
  check('PNG export contains a valid rendered image', png[0] === 137 && png[1] === 80 && png.length > 10000)
  await screenshot('phase2-board')

