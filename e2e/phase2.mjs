  await page.keyboard.press('Escape'); await page.keyboard.press('Escape')

  await page.keyboard.press('r'); await gesture(page, [[640, 180], [900, 300]])
  await page.keyboard.press('v'); await gesture(page, [[770, 240]])
  check('unfilled shapes can be selected through their interior', await fw(page, w => w.board.selection[0]?.k === 'rect'))
  await page.keyboard.press('Enter')
  const label = page.getByRole('textbox', { name: 'Shape label' })
  await label.fill('Start with an idea'); await label.press('Control+Enter')
