  const beforeResize = await fw(page, w => structuredClone(w.board.selection[0]))
  await gesture(page, [[b[2], b[3]], [b[2] + 70, b[3] + 40]])
  check('corner handle resizes the object', await fw(page, (w, before) => w.board.selection[0].p[2] - w.board.selection[0].p[0] > before.p[2] - before.p[0] + 50, beforeResize))
  await page.keyboard.press('Control+z')
  check('one undo restores the entire resize', await fw(page, (w, before) => JSON.stringify(w.board.selection[0]) === JSON.stringify(before), beforeResize))
  const rotBounds = await selectBox(), center = [(rotBounds[0] + rotBounds[2]) / 2, (rotBounds[1] + rotBounds[3]) / 2]
  check('rotation handle is not covered by the selection toolbar', await page.evaluate(([x, y]) => document.elementFromPoint(x, y)?.classList.contains('stage'), [center[0], rotBounds[1] - 28]))
  await gesture(page, [[center[0], rotBounds[1] - 28], [rotBounds[2] + 28, center[1]]], { shift: true })
  check('rotation handle rotates the shape and label together', await fw(page, w => Math.abs(w.board.selection[0].angle - Math.PI / 2) < .001))
  await page.keyboard.press('Control+z')

  await page.keyboard.press('Control+a'); await page.keyboard.press('Control+g')
  const group = await fw(page, w => w.board.selection[0].group)
  check('grouping creates one persistent group', await fw(page, (w, g) => !!g && w.board.selection.length === 3 && w.board.selection.every(it => it.group === g), group))
  await page.keyboard.press('Control+d')
  check('duplicated groups have independent IDs and membership', await fw(page, (w, g) => w.board.doc.items.length === 6 && w.board.selection.every(it => it.group && it.group !== g) && new Set(w.board.doc.items.map(it => it.id)).size === 6, group))
  await page.keyboard.press('Control+z')
  await page.keyboard.press('Control+a'); await page.keyboard.press('Control+Shift+g')
  check('ungroup keeps all objects and clears membership', await fw(page, w => w.board.doc.items.length === 3 && w.board.selection.every(it => !it.group)))

  await fw(page, w => w.board.setSelection([w.board.doc.items[1]]))
  await page.keyboard.press('Control+l')
  const lockedBefore = await fw(page, w => JSON.stringify(w.board.selection[0]))
  await gesture(page, [[250, 440], [310, 450]])
  await page.keyboard.press('Delete')
  check('locked note can be selected but cannot be moved or deleted', await fw(page, (w, before) => w.board.doc.items.length === 3 && JSON.stringify(w.board.doc.items[1]) === before, lockedBefore))
  await page.getByRole('button', { name: 'Unlock selection', exact: true }).click()
  check('unlock is available directly on the selection', await fw(page, w => !w.board.selection[0].locked))
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('Shift+ArrowDown')
  check('keyboard nudge supports fine and coarse steps', await fw(page, w => w.board.selection[0].p[0] === 201 && w.board.selection[0].p[1] === 400))

  await page.keyboard.press('Control+c'); await page.keyboard.press('Control+v')
  check('object copy and paste keeps text and styling editable', await fw(page, w => w.board.doc.items.length === 4 && w.board.selection[0].note && w.board.selection[0].text.includes('Lesson')))
  await page.keyboard.press('Control+z')
  await page.keyboard.press('Escape'); await page.keyboard.press('q')
  await gesture(page, [[175, 375], [455, 375], [455, 650], [175, 650], [175, 375]])
  check('lasso selects the enclosed note', await fw(page, w => w.board.selection.length === 1 && w.board.selection[0].note))
  await page.keyboard.press('v')

  // User-facing edit focus and cancellation must leave both content and history intact.
  await page.keyboard.press('Enter')
  await page.getByRole('textbox', { name: 'Sticky note text' }).fill('Discard this edit')
  await page.keyboard.press('Escape')
  check('Escape restores original text and exits inline editing', await fw(page, w => !w.S.editing.value && w.board.selection[0].text.includes('Lesson')))

  await page.keyboard.press('Control+a')
  const plainTextBefore = await fw(page, w => JSON.stringify(w.board.doc.items.find(it => it.t === 't' && !it.note)))
  await page.getByRole('button', { name: 'Object style', exact: true }).click()
  await page.getByRole('button', { name: 'Fill #e7d9ff', exact: true }).click()
  check('mixed selection fill changes only compatible objects', await fw(page, (w, before) => JSON.stringify(w.board.doc.items.find(it => it.t === 't' && !it.note)) === before && w.board.doc.items.filter(it => it.note || it.t === 'h').every(it => it.fill === '#e7d9ff'), plainTextBefore))
  await page.keyboard.press('Escape'); await page.keyboard.press('Control+z')
  await fw(page, w => w.board.setSelection([w.board.doc.items.find(it => it.t === 'h')]))
  await page.keyboard.press('Control+Alt+c')
  await fw(page, w => w.board.setSelection([w.board.doc.items.find(it => it.note)]))
  await page.keyboard.press('Control+Alt+v')
  check('pasting a default style clears previous bold and list formatting', await fw(page, w => w.board.selection[0].list === 'none' && w.board.selection[0].bold === false && w.board.selection[0].fill === '#d7f0dd'))
  await page.keyboard.press('Control+z')

