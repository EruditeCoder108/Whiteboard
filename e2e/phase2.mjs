  await page.keyboard.press('Escape'); await page.keyboard.press('Escape')

  await page.keyboard.press('n'); await gesture(page, [[200, 390]])
  const note = page.getByRole('textbox', { name: 'Sticky note text' })
  await note.fill('Lesson ideas\nKeep objects editable\nUndo every step')
  await note.press('Control+Enter')
  await page.getByRole('button', { name: 'Object style', exact: true }).click()
  await page.getByRole('button', { name: 'Fill #d3e6ff', exact: true }).click()
  await page.getByRole('button', { name: 'Bulleted list', exact: true }).click()
